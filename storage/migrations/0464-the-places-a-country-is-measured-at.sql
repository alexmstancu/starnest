-- The five largest places of each country, where a coordinate-bound source measures it (D4).
--
-- Decided by the household on 2026-09-11 (`devplan.md` D4, `reqs.md` Q210): a national climate
-- figure is the **population-weighted mean over the country's largest places**. A centroid
-- gives Spain the climate of an empty plateau and a capital gives Italy only Rome; neither
-- describes where anyone would live. A grid mean describes Norway's empty north.
--
-- **Sourced, never typed from memory.** GeoNames (geonames.org, CC BY 4.0 -- attribution is the
-- `data_source` row below), dump `cities5000` of 2026-09-11: every place of 5,000 people or more,
-- with coordinates and population. `backend/scripts/population_centres.py` writes these rows from
-- the dump, so they can be regenerated and checked. Places only (`PPL` and its administrative
-- variants), never `PPLX`, a section of a place, which would count one city's districts as
-- several cities. Suburbs GeoNames records as places of their own stay (Petrzalka, Tallaght):
-- they share their city's climate, and so weight it more, which is what their people do.
--
-- Liechtenstein's towns are all near 5,000 people and Malta's are localities of one conurbation;
-- both still have five, and a smaller country simply has smaller places.
-- depends: 0463-working-hours-and-networks-join-the-minimal-set

INSERT INTO data_source (id, name, source_kind, default_priority, reliability_tier)
VALUES ('geonames', 'GeoNames (CC BY 4.0)', 'structured', 64, 'crowdsourced')
ON CONFLICT (id) DO NOTHING;

CREATE TABLE population_centre (
    geonames_id  bigint       PRIMARY KEY,
    candidate    text         NOT NULL REFERENCES candidate (id),
    name         text         NOT NULL,
    latitude     numeric(8,5) NOT NULL,
    longitude    numeric(8,5) NOT NULL,
    population   integer      NOT NULL,
    data_source  text         NOT NULL REFERENCES data_source (id),
    retrieved_on date         NOT NULL,

    CONSTRAINT population_centre_is_on_the_globe
        CHECK (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180),
    -- The weight of a place in the mean. A place of nobody would be a point that counts for
    -- nothing, or divides by zero.
    CONSTRAINT population_centre_has_people CHECK (population > 0)
);

COMMENT ON TABLE population_centre IS
    'Where a coordinate-bound source measures a country: its largest places, weighted by population (devplan.md D4, reqs.md Q210). Reference geography, sourced from GeoNames.';

